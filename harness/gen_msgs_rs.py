import json
msgs = json.load(open("harness/messages.json"))
out = []
out.append("//! GENERATED by harness/gen_msgs_rs.py from pylint 4.0.5 message store. Do not edit.")
out.append("")
out.append("pub struct MessageDef {")
out.append("    pub msgid: &'static str,")
out.append("    pub symbol: &'static str,")
out.append("    pub template: &'static str,")
out.append("    /// enabled under `-E --disable=<target list>`")
out.append("    pub enabled: bool,")
out.append("    /// pylint WarningScope: true = node-based (block pragma expansion), false = line-based")
out.append("    pub node_scope: bool,")
out.append("    pub old_names: &'static [(&'static str, &'static str)],")
out.append("}")
out.append("")
out.append("pub static MESSAGES: &[MessageDef] = &[")
for m in msgs:
    old = ", ".join(f'("{o[0]}", "{o[1]}")' for o in m["old_names"])
    tmpl = m["template"].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    node_scope = "true" if m["scope"] == "node-based-msg" else "false"
    out.append(f'    MessageDef {{ msgid: "{m["msgid"]}", symbol: "{m["symbol"]}", template: "{tmpl}", enabled: {str(m["enabled"]).lower()}, node_scope: {node_scope}, old_names: &[{old}] }},')
out.append("];")
open("crates/pycheckers/src/msgs.rs", "w").write("\n".join(out) + "\n")
print(f"{len(msgs)} messages -> crates/pycheckers/src/msgs.rs")
